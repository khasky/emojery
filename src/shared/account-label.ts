// FNV-1a: a few characters in, one number out, the same on every engine. Not a
// security boundary - the id it folds is already on this device.
function fold(text: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < text.length; i += 1) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash;
}

/** The mark for an account id: one emoji, e.g. `🦅`. */
export function accountLabel(userId: string): string {
  return MARKS[fold(userId) % MARKS.length] as string;
}
