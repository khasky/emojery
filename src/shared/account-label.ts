// FNV-1a: a spread, not a secret. The id it folds is already a one-way hash, and a
// label that says nothing about the account is the point - so speed and no
// dependency beat a cryptographic digest, which would also force this async.
function fold(text: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < text.length; i += 1) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash;
}

/** The label for an account id: two lowercase words, e.g. `quiet-heron`. */
export function accountLabel(userId: string): string {
  const hash = fold(userId);
  return `${ADJECTIVES[hash & 0xff]}-${NOUNS[(hash >>> 8) & 0xff]}`;
}
